// transcoding and the JPEG's reconstruction, lossless encoding of pixels, decoding,
// rectangles of an image decoded into a bitmap, and what a file's header tells. libjxl
// is not built here: jxl-coder ships it whole (libjxl.so, exporting the public C API),
// so it is opened at run time and compiled against the headers of the same release
// (CMakeLists.txt). Each call is single-threaded but nRegion, which runs on
// libjxl_threads.so's thread pool when it is there, and nPage, on its own pinned pool
// (jxl_page.c).

